import turtle

turtle.shape("turtle")
turtle.speed(10)



turtle.pencolor("red")
turtle.fillcolor("blue")
turtle.begin_fill()
turtle.pendown()
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.penup()
turtle.end_fill()



turtle.goto(50,100)
turtle.pendown()
turtle.begin_fill()
turtle.pendown()
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.right(90)
turtle.forward(30)
turtle.penup()
turtle.end_fill()






turtle.done()